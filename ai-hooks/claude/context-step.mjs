#!/usr/bin/env node
// Claude Code, PostToolUse: тот же порог контекста, но посреди хода — между
// вызовами инструментов.
//
// Зачем отдельный хук. `context-meter.mjs` висит на `UserPromptSubmit`, то есть
// считает раз на сообщение пользователя. Ход, где агент сам разбил работу на
// шаги и идёт по ним сотней вызовов, не даёт ему сработать ни разу: в сессии
// `1fcabed0` окно выросло с 27k до 318k на одном промпте, и первое (оно же
// единственное) предупреждение прозвучало уже на 303k. Порогов для автономного
// хода попросту не существовало.
//
// Почему не «остановись немедленно». Обрыв посреди хода оставляет незакоммиченное
// рабочее дерево и половину шага, которую нечем описать в блоке передачи: новой
// сессии достаётся не задача, а развал. Поэтому текст порога требует довести
// текущий шаг и только следующий отдать новой сессии через `handoff`.
//
// Повтор ограничен ростом контекста (`STEP_REPEAT`), а не числом вызовов: на
// каждом вызове напоминание стоило бы дороже того, что экономит.

import { contextNotice, noteWork } from '../context-core.mjs';
import { isEntryPoint } from '../state-core.mjs';
import { runHook } from './hook-io.mjs';

export function check(input) {
  // Сначала отметка о работе, потом замер: именно здесь видно имя инструмента,
  // а от него зависит, есть ли в сессии что передавать и какой текст порога верен.
  noteWork(input);
  const notice = contextNotice(input, { phase: 'step' });
  return notice ? { context: notice.text } : null;
}

if (isEntryPoint(import.meta.url)) runHook(check, 'PostToolUse');
